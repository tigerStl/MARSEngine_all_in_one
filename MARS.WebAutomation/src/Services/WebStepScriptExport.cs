using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using MARS.WebAutomation.Models;

namespace MARS.WebAutomation.Services
{
    /// <summary>Builds TypeScript snippets for Playwright / Selenium from <see cref="SemanticStepRecord"/> lists.</summary>
    public static class WebStepScriptExport
    {
        public static string GetExportScriptsDirectory(string dataRootFolder)
        {
            var root = string.IsNullOrWhiteSpace(dataRootFolder)
                ? DataPathHelper.GetAssemblyBaseDirectory()
                : dataRootFolder.Trim();
            var dir = System.IO.Path.Combine(root, "export", "scripts");
            System.IO.Directory.CreateDirectory(dir);
            return dir;
        }

        public static string BuildPlaywrightTypeScript(IReadOnlyList<SemanticStepRecord> steps)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// Auto-generated by MARS.WebAutomation");
            sb.AppendLine("import { test, expect } from '@playwright/test';");
            sb.AppendLine();
            sb.AppendLine("test.describe('MARS Web export', () => {");
            sb.AppendLine("  test('steps', async ({ page }) => {");
            var firstUrl = steps.FirstOrDefault(s => !string.IsNullOrWhiteSpace(s?.RecordedPageUrl))?.RecordedPageUrl;
            if (!string.IsNullOrWhiteSpace(firstUrl))
                sb.AppendLine("    await page.goto(" + TsString(firstUrl.Trim()) + ");");
            var i = 0;
            foreach (var s in steps)
            {
                if (s == null || string.IsNullOrWhiteSpace(s.Keyword))
                    continue;
                i++;
                var kw = s.Keyword.Trim();
                if (IsNoiseKeyword(kw))
                {
                    sb.AppendLine("    // Step " + i + ": " + kw + " (skipped)");
                    continue;
                }
                var line = TryPlaywrightLine(s);
                if (string.IsNullOrWhiteSpace(line))
                {
                    sb.AppendLine("    // Step " + i + ": " + kw + " — add manually");
                    continue;
                }
                sb.AppendLine("    // Step " + i + ": " + kw);
                sb.AppendLine("    " + line.Trim());
            }
            sb.AppendLine("  });");
            sb.AppendLine("});");
            return sb.ToString();
        }

        public static string BuildSeleniumTypeScript(IReadOnlyList<SemanticStepRecord> steps)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// Auto-generated by MARS.WebAutomation");
            sb.AppendLine("import { Builder, By, until } from 'selenium-webdriver';");
            sb.AppendLine();
            sb.AppendLine("async function runExportedSteps(): Promise<void> {");
            sb.AppendLine("  const driver = await new Builder().forBrowser('chrome').build();");
            sb.AppendLine("  try {");
            var firstUrl = steps.FirstOrDefault(s => !string.IsNullOrWhiteSpace(s?.RecordedPageUrl))?.RecordedPageUrl;
            if (!string.IsNullOrWhiteSpace(firstUrl))
                sb.AppendLine("    await driver.get(" + TsString(firstUrl.Trim()) + ");");
            var i = 0;
            foreach (var s in steps)
            {
                if (s == null || string.IsNullOrWhiteSpace(s.Keyword))
                    continue;
                i++;
                var kw = s.Keyword.Trim();
                if (IsNoiseKeyword(kw))
                {
                    sb.AppendLine("    // Step " + i + ": " + kw + " (skipped)");
                    continue;
                }
                var line = TrySeleniumLine(s);
                if (string.IsNullOrWhiteSpace(line))
                {
                    sb.AppendLine("    // Step " + i + ": " + kw + " — add manually");
                    continue;
                }
                sb.AppendLine("    // Step " + i + ": " + kw);
                sb.AppendLine("    " + line.Trim());
            }
            sb.AppendLine("  } finally {");
            sb.AppendLine("    await driver.quit();");
            sb.AppendLine("  }");
            sb.AppendLine("}");
            sb.AppendLine();
            sb.AppendLine("void runExportedSteps();");
            return sb.ToString();
        }

        private static bool IsNoiseKeyword(string kw)
        {
            return string.Equals(kw, "Pegwindow", StringComparison.OrdinalIgnoreCase)
                || string.Equals(kw, "PegwindowMove", StringComparison.OrdinalIgnoreCase);
        }

        private static string TryPlaywrightLine(SemanticStepRecord s)
        {
            if (!string.IsNullOrWhiteSpace(s.PlaywrightScript))
            {
                var t = s.PlaywrightScript.Trim();
                if (!t.EndsWith(";", StringComparison.Ordinal))
                    t += ";";
                return t;
            }
            var loc = PrimaryCssLocator(s);
            if (string.IsNullOrWhiteSpace(loc))
                return null;
            var pw = "page.locator(" + TsString(loc) + ")";
            var kw = s.Keyword.Trim();
            if (string.Equals(kw, "FillEdit", StringComparison.OrdinalIgnoreCase))
            {
                var v = CoalesceData(s);
                return "await " + pw + ".fill(" + TsString(v) + ");";
            }
            if (string.Equals(kw, "SelectDropDown", StringComparison.OrdinalIgnoreCase))
            {
                var label = CoalesceData(s);
                return "await " + pw + ".selectOption({ label: " + TsString(label) + " });";
            }
            if (string.Equals(kw, "SetBox", StringComparison.OrdinalIgnoreCase))
            {
                var on = string.Equals(s.Data?.Trim(), "true", StringComparison.OrdinalIgnoreCase);
                return "await " + pw + ".setChecked(" + (on ? "true" : "false") + ");";
            }
            if (string.Equals(kw, "FileBrowser", StringComparison.OrdinalIgnoreCase))
                return null;
            if (string.Equals(kw, "FillTable", StringComparison.OrdinalIgnoreCase))
                return null;
            if (string.Equals(kw, "AssertElementState", StringComparison.OrdinalIgnoreCase))
            {
                var par = (s.Parameter ?? string.Empty).Trim();
                return "// AssertElementState: " + TsString(par) + " — use expect() on properties; see Mars keyword impl.";
            }
            if (string.Equals(kw, "AssertLocatorCount", StringComparison.OrdinalIgnoreCase))
            {
                var par = (s.Parameter ?? string.Empty).Trim();
                return "// AssertLocatorCount: " + pw + "; Parameter=" + TsString(par) + " (add expect().toHaveCount after setting Expected=)";
            }
            if (string.Equals(kw, "AssertScreenshot", StringComparison.OrdinalIgnoreCase))
                return "// AssertScreenshot: use expect(page).toHaveScreenshot or locator screenshot compare; Parameter=" + TsString((s.Parameter ?? string.Empty).Trim());
            return "await " + pw + ".click();";
        }

        private static string TrySeleniumLine(SemanticStepRecord s)
        {
            var loc = PrimaryCssLocator(s);
            if (string.IsNullOrWhiteSpace(loc))
                return null;
            var by = SeleniumByFromLocator(loc);
            var kw = s.Keyword.Trim();
            if (string.Equals(kw, "FillEdit", StringComparison.OrdinalIgnoreCase))
                return "await driver.findElement(" + by + ").sendKeys(" + TsString(CoalesceData(s)) + ");";
            if (string.Equals(kw, "SelectDropDown", StringComparison.OrdinalIgnoreCase))
            {
                // Best-effort: open then pick option by visible text (adjust if your <select> needs keys)
                return "await driver.findElement(" + by + ").click(); // SelectDropDown: refine option by label " + TsString(CoalesceData(s));
            }
            if (string.Equals(kw, "SetBox", StringComparison.OrdinalIgnoreCase))
                return "await driver.findElement(" + by + ").click();";
            if (string.Equals(kw, "FileBrowser", StringComparison.OrdinalIgnoreCase) || string.Equals(kw, "FillTable", StringComparison.OrdinalIgnoreCase))
                return null;
            return "await driver.findElement(" + by + ").click();";
        }

        private static string CoalesceData(SemanticStepRecord s)
        {
            if (!string.IsNullOrEmpty(s.Data))
                return s.Data;
            return string.Empty;
        }

        private static string SeleniumByFromLocator(string loc)
        {
            var t = loc.Trim();
            if (t.StartsWith("//", StringComparison.Ordinal) || t.StartsWith("(//", StringComparison.Ordinal))
                return "By.xpath(" + TsString(t) + ")";
            return "By.css(" + TsString(t) + ")";
        }

        private static string PrimaryCssLocator(SemanticStepRecord s)
        {
            if (s == null)
                return string.Empty;
            if (string.Equals(s.Keyword, "SelectTab", StringComparison.OrdinalIgnoreCase)
                && !string.IsNullOrWhiteSpace(s.TargetLocator))
                return s.TargetLocator.Trim();
            return (s.Locator ?? string.Empty).Trim();
        }

        private static string TsString(string s)
        {
            if (s == null)
                return "''";
            return "'" + s.Replace("\\", "\\\\").Replace("'", "\\'").Replace("\r", "\\r").Replace("\n", "\\n") + "'";
        }
    }
}
