create PROCEDURE [dbo].[SP_IMPORT_APP] (
@BatchId  bigint
)
as
begin

	MERGE T_REGISTERED_APPS as tag
	using (
		select APPNAME,PROCESSIDENTIFIER,STARTERPATH,STARTERCMD,VERSION,
		COMMENT,APPTYPE,RECORDBY,EXTRAREQUIREMENT,MODE,EXPLORERBIT from  TEMP_IMPORT_APP where BATCHID= @BatchId
		) as source on tag.APP_SHORT_NAME =source.APPNAME
	WHEN MATCHED THEN
		update set tag.PROCESS_IDENTIFIER =source.PROCESSIDENTIFIER ,
		tag.STARTER_PATH=source.STARTERPATH,tag.STARTER_COMMAND=source.STARTERCMD,tag.VERSION=source.VERSION,
		tag.COMMENT=source.COMMENT,tag.APPLICATION_TYPE_ID=source.APPTYPE,tag.RECORD_CREATE_PERSON=source.RECORDBY,
			tag.EXTRAREQUIREMENT=source.EXTRAREQUIREMENT,
		tag.ISBASELINE=source.MODE,tag.IS64BIT=source.EXPLORERBIT
	WHEN NOT MATCHED BY TARGET THEN
		INSERT (APP_SHORT_NAME,PROCESS_IDENTIFIER,STARTER_PATH,STARTER_COMMAND,VERSION,
		COMMENT,APPLICATION_TYPE_ID,RECORD_CREATE_PERSON,RECORD_CREATE_DATE,EXTRAREQUIREMENT,
		ISBASELINE,IS64BIT)
		VALUES ( source.APPNAME, source.PROCESSIDENTIFIER, source.STARTERPATH,
		source.STARTERCMD,source.VERSION, source.COMMENT, source.APPTYPE,source.RECORDBY, GetDate(),
		source.EXTRAREQUIREMENT, source.MODE,source.EXPLORERBIT);

end  ;
