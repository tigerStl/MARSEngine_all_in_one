CREATE PROCEDURE [dbo].[SP_IMPORT_KEYWORD] (@BatchId  bigint)
as
begin

	MERGE T_keyword as tag
	using (
		select  t.keyword_name,t.name_description from  TEMP_IMPORT_KEYWORD t
		where t.batch_id= @BatchId and t.data_type=1
		) as source on tag.KEY_WORD_NAME =source.keyword_name
	WHEN MATCHED THEN
		update set tag.DESCRIPTION =source.name_description  
	WHEN NOT MATCHED BY TARGET THEN
		INSERT (KEY_WORD_NAME,DESCRIPTION)
		VALUES ( source.keyword_name, source.name_description);

	MERGE T_GUI_COMPONENT_TYPE_DIC as tag
	using (
		select  t.keyword_name,t.name_description from  TEMP_IMPORT_KEYWORD t
		where t.batch_id= @BatchId and t.data_type=2
		) as source on tag.TYPE_NAME =source.keyword_name
	WHEN MATCHED THEN
		update set tag.DESCRIPTION =source.name_description  
	WHEN NOT MATCHED BY TARGET THEN
		INSERT (TYPE_NAME,DESCRIPTION)
		VALUES (source.keyword_name, source.name_description);

	MERGE T_DIC_RELATION_KEYWORD as tag
	using (
		select  t.keyword_name,t.name_description ,g.TYPE_ID,k.KEY_WORD_ID from TEMP_IMPORT_KEYWORD t
		join T_GUI_COMPONENT_TYPE_DIC g on g.TYPE_NAME =t.name_description
		join T_KEYWORD k on k.KEY_WORD_NAME= t.keyword_name
		where t.batch_id= @BatchId and t.data_type=3
		) as source on tag.TYPE_ID =source.TYPE_ID and tag.KEY_WORD_ID =source.KEY_WORD_ID 
	WHEN NOT MATCHED BY TARGET THEN
		INSERT (KEY_WORD_ID,TYPE_ID)
		VALUES (source.KEY_WORD_ID, source.TYPE_ID);

end  ;
